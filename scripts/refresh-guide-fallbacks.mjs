// Refreshes the checked-in records behind the city category guides
// (restaurants, bars, cafés and hotels). The build prefers live public data and
// uses these records only when the API is unavailable or PRERENDER_OFFLINE=1.
// Run with: npm run refresh:guides
import fs from 'node:fs/promises'
import { loadEnv } from 'vite'
import { buildPlacesUrl, cityGuides, resolveCityGuide, selectPlaces } from '../src/cityGuides.js'

const env = { ...loadEnv('production', process.cwd(), 'VITE_'), ...process.env }
if (!env.VITE_SUPABASE_URL || !env.VITE_SUPABASE_ANON_KEY) throw new Error('VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY are required')

const guides = Object.values(cityGuides)
  .flatMap((city) => Object.keys(city.topics || {}).map((topic) => resolveCityGuide(city.slug, topic)))
  .filter((guide) => guide.fallbackPlaces.length === 0)

const records = {}
for (const guide of guides) {
  const response = await fetch(buildPlacesUrl(guide, env.VITE_SUPABASE_URL), {
    headers: { apikey: env.VITE_SUPABASE_ANON_KEY, Authorization: `Bearer ${env.VITE_SUPABASE_ANON_KEY}` },
    signal: AbortSignal.timeout(15000),
  })
  if (!response.ok) throw new Error(`${guide.path}: public places returned ${response.status}`)
  const places = selectPlaces(guide, await response.json())
  if (!places.length) throw new Error(`${guide.path}: no public records`)
  records[guide.fallbackKey] = places
  console.log(`[refresh] ${guide.path}: ${places.map((place) => place.name).join(' · ')}`)
}

await fs.writeFile('src/cityGuideTopicPlaces.js',
  `// Generated by scripts/refresh-guide-fallbacks.mjs from public YouKnow place records.\n// Do not edit by hand; run \`npm run refresh:guides\`.\nexport default ${JSON.stringify(records, null, 2)}\n`)
console.log(`[refresh] ${guides.length} category guides written to src/cityGuideTopicPlaces.js`)
